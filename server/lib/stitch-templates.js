const BY_ID = new Map(STITCH_TEMPLATES.map((t) => [t.id, t]));

/** @param {string} id */
export function templateById(id) {
  return BY_ID.get(String(id || '')) || null;
}

/** 当前张数可用的模板（模板是为人眼构图定死的，张数不对就会留空） */
export function templatesFor(n) {
  return STITCH_TEMPLATES.filter((t) => n >= t.min && n <= t.max);
}

/** 画布比例 → [w, h]；模板里写的是 '2:3' 这种字符串 */
export function ratioOf(spec) {
  const m = String(spec || '').match(/^(\d+(?:\.\d+)?)\s*[:/]\s*(\d+(?:\.\d+)?)$/);
  if (!m) return [4, 3];
  const w = Number(m[1]);
  const h = Number(m[2]);
  if (!(w > 0 && h > 0)) return [4, 3];
  return [w, h];
}

/**
 * 模板 → 绝对像素几何（纯计算，不碰文件）。
 * @param {Template} tpl
 * @param {number} W 画布宽
 * @param {number} n 实际张数
 * @param {{gap?:number, seamless?:boolean}} [opts]
 */
export function templateBoxes(tpl, W, n, opts = {}) {
  const [rw, rh] = ratioOf(tpl.ratio);
  const H = Math.max(2, Math.round((W * rh) / rw));
  const short = Math.min(W, H);
  // 无缝：贴边排列、格子之间零缝隙，模板的留白也一并取消
  const seamless = opts.seamless === undefined ? Boolean(tpl.seamless) : Boolean(opts.seamless);
  const padPx = seamless ? 0 : Math.round((tpl.pad || 0) * short);
  const gapRaw = Number(opts.gap);
  const gapDefault = tpl.gap ? Math.round(tpl.gap * short) : Math.round(W * 0.009);
  const gap = seamless ? 0 : Number.isFinite(gapRaw) ? Math.min(120, Math.max(0, gapRaw)) : gapDefault;
  const inset = Math.round(gap / 2);
  const iw = W - padPx * 2;
  const ih = H - padPx * 2;
  // 边界先各自取整再相减：相邻两格共用同一个像素边界，无缝时才不会露 1px 白线
  const edge = (v, base) => Math.round(base + v);
  const boxes = [];
  const count = Math.min(n, tpl.slots.length);
  for (let i = 0; i < count; i++) {
    const s = tpl.slots[i];
    const x0 = edge(s[0] * iw, padPx);
    const x1 = edge((s[0] + s[2]) * iw, padPx);
    const y0 = edge(s[1] * ih, padPx);
    const y1 = edge((s[1] + s[3]) * ih, padPx);
    // 每格四周内缩 gap/2：格子之间和画布边缘都留出同样的缝，观感才匀
    boxes.push({
      idx: i,
      x: x0 + inset,
      y: y0 + inset,
      w: Math.max(4, x1 - x0 - inset * 2),
      h: Math.max(4, y1 - y0 - inset * 2),
    });
  }
  return { boxes, W, H, padPx, gap, short, slotCount: count, seamless };
}
